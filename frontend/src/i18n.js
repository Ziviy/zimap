export const getI18n = (lang) => {
  return (key) => {
    const keys = key.split('.');
    let current = translations[lang] || translations['en'];
    for (const k of keys) {
      if (current[k] === undefined) {
        return key;
      }
      current = current[k];
    }
    return current;
  };
};
